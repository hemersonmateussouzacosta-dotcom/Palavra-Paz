// Complete list generator for all 150 Psalms with thematic titles & classifications
export function getAll150PsalmsDirectory(): { number: number; title: string; theme: string; isCurated: boolean }[] {
  const themes = [
    'Louvor & Adoração',
    'Proteção & Refúgio',
    'Súplica & Alívio',
    'Sabedoria & Instrução',
    'Ação de Graças',
    'Confiança & Esperança',
    'Perdão & Restauração'
  ];

  return Array.from({ length: 150 }, (_, i) => {
    const num = i + 1;
    const curated = CURATED_PSALMS.find((p) => p.number === num);
    if (curated) {
      return {
        number: num,
        title: curated.title,
        theme: curated.theme,
        isCurated: true
      };
    }
    const theme = themes[num % themes.length];
    return {
      number: num,
      title: `Salmo ${num} • Cântico de Davi e dos Filhos de Corá`,
      theme,
      isCurated: false
    };
  });
}

// Dedicated function to retrieve the Psalm of the Day based on a calendar date
export function getDailyPsalm(dateStr?: string): Psalm {
  const targetDate = dateStr ? new Date(dateStr + 'T12:00:00') : new Date();
  
  // Calculate day-of-year index
  const startOfYear = new Date(targetDate.getFullYear(), 0, 0);
  const diff = targetDate.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);

  // Map to curated psalms in rotation, or to the 150 psalms
  const index = Math.abs(dayOfYear) % CURATED_PSALMS.length;
  const psalm = CURATED_PSALMS[index];
  if (psalm) {
    return psalm;
  }

  // Fallback to Psalm 23 or 91
  return CURATED_PSALMS[1] || CURATED_PSALMS[0];
}
